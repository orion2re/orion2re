#!/usr/bin/env python3
"""Translate the canonical integer scaler kernels into a Vulkan compute shader."""
import argparse
from pathlib import Path
import re


def translate(text):
    text = text.replace("inline ", "").replace("uint32_t", "uint").replace("int32_t", "int")
    text = text.replace("(uint)", "uint")
    text = re.sub(r"const int ([yuv][12]) = ([^;]+);", r"int \1 = int(\2);", text)
    text = text.replace("const uint* pixels", "uint pixels[9]").replace("const uint* yuv", "uint yuv[9]")
    text = text.replace("uint* destination", "inout uint destination[16], int destination_offset")
    text = re.sub(r"uint\* dst(\d+) = &destination\[([^;]+)\];",
                  r"int dst\1 = destination_offset + \2;", text)
    text = re.sub(r"\*dst(\d+)", r"destination[dst\1]", text)
    for name in ("weight1", "weight2", "weight3"):
        text = text.replace("* " + name, "* uint(" + name + ")")
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    hqx = (args.source / "hqx.cpp").read_text()
    mmpx = (args.source / "mmpx.cpp").read_text()
    # Preserve the upstream notices in the generated shader.
    licenses = "\n".join(re.search(r"/\*.*?\*/", source, re.S).group() for source in (hqx, mmpx))
    helpers = hqx[hqx.index("uint32_t RGB_To_YUV"):hqx.index("inline uint32_t Lookup_YUV")]
    helpers += '''uint Lookup_YUV(uint color) {
        int r = int((color >> 19) & 31), g = int((color >> 10) & 63), b = int((color >> 3) & 31);
        return RGB_To_YUV((r << 3) | (r >> 2), (g << 2) | (g >> 4), (b << 3) | (b >> 2));
    }
'''
    helpers += hqx[hqx.index("inline bool YUV_Diff"):hqx.index("#define P(")]
    interpolation = hqx[hqx.index("inline uint32_t HQ2x_Interpolate"):hqx.index("void Convert_YUV_Row")]
    for rotation in ("0", "rotate"):
        shuffled = " | ".join(
            f"(((pattern >> (({rotation}) != 0 ? {7 - (i if i < 4 else i - 1)} : {i if i < 4 else i - 1})) & 1) << (p{i} > 4 ? p{i} - 1 : p{i}))"
            for i in (0, 1, 2, 3, 5, 6, 7, 8))
        bootstrap = f"int shuffled_pattern = {shuffled};\n"
        bootstrap += "\n".join(f"uint w{i} = pixels[p{i}];" for i in (0, 1, 3, 4, 5, 7))
        bootstrap += "\n" + "\n".join(f"uint y{i} = yuv[p{i}];" for i in (0, 1, 3, 5, 7))
        interpolation = interpolation.replace(f"INTERP_BOOTSTRAP({rotation});", bootstrap)
    helpers = translate(helpers + interpolation)
    mmpx_helpers = translate(mmpx[mmpx.index("inline uint32_t Luma"):mmpx.index("inline int32_t Clamp")])
    kernel = mmpx[mmpx.index("uint32_t j = e;"):mmpx.index("output_top[0] = j;")]
    row_offsets = {"row": 0, "row_n1": -1, "row_n2": -2, "row_n3": -3,
                   "row_s1": 1, "row_s2": 2, "row_s3": 3}
    for row, offset in row_offsets.items():
        kernel = re.sub(r"Row_Pixel\(" + row + r", source_width, ([^)]+)\)",
                        lambda m: f"Read(ivec2({m[1]}, y + ({offset})))", kernel)
        kernel = kernel.replace(f"{row}[x]", f"Read(ivec2(x, y + ({offset})))")
    kernel = translate(kernel)
    mmpx_shader = '''void MMPX(ivec2 coord, out uint output[16]) {
        int x = coord.x, y = coord.y;
'''
    for i, letter in enumerate("abcdefghi"):
        mmpx_shader += f"uint {letter} = Read(coord + ivec2({i % 3 - 1}, {i // 3 - 1}));\n"
    mmpx_shader += "uint q = Read(coord + ivec2(-2, 0)), r = Read(coord + ivec2(2, 0));\n"
    mmpx_shader += kernel + "output[0] = j; output[1] = k; output[2] = l; output[3] = m;\n}\n"
    calls = hqx[hqx.index("if constexpr (Factor == 2)"):hqx.index("const int32_t new_x", hqx.index("if constexpr (Factor == 2)"))]
    calls = calls.replace("if constexpr (Factor == 2)", "if (params.factor == 2)").replace("else if constexpr (Factor == 3)", "else if (params.factor == 3)")
    calls = calls.replace("destination_stride", "params.factor")
    # Convert output pointer offsets to an explicit destination-array offset.
    calls = re.sub(r"HQ([34])x_Interpolate\(output(.*?), params.factor,", r"HQ\1x_Interpolate(output, 0\2, params.factor,", calls)
    shader = '''#version 450
// Generated by tools/generate_scaler_shader.py from hqx.cpp and mmpx.cpp.
'''+ licenses + '''
layout(local_size_x=8, local_size_y=8, local_size_z=1) in;
layout(set=0, binding=0) uniform sampler2D source_texture;
layout(set=1, binding=0, rgba8) uniform writeonly image2D output_texture;
layout(set=2, binding=0, std140) uniform Parameters { ivec2 size; int mode; int factor; } params;
uint Read(ivec2 coord) {
    uvec4 c = uvec4(round(texelFetch(source_texture, clamp(coord, ivec2(0), params.size-1), 0)*255.0));
    return (c.a << 24) | (c.r << 16) | (c.g << 8) | c.b;
}
void Write(ivec2 coord, uint color) {
    imageStore(output_texture, coord, vec4((color >> 16) & 255, (color >> 8) & 255, color & 255, color >> 24)/255.0);
}
#define P(mask, result) ((shuffled_pattern & (mask)) == (result))
#define WDIFF(yuv1, yuv2) YUV_Diff(yuv1, yuv2)
'''+helpers+mmpx_helpers+mmpx_shader+'''
void main() {
    ivec2 coord = ivec2(gl_GlobalInvocationID.xy);
    if (any(greaterThanEqual(coord, params.size))) return;
    uint output[16];
    if (params.mode == 0 || params.mode == 1) { Write(coord, Read(coord)); return; }
    if (params.mode == 5 || params.mode == 11) { MMPX(coord, output); }
    else {
        uint pixels[9], yuv[9];
        for (int i=0; i<9; ++i) { pixels[i]=Read(coord+ivec2(i%3-1,i/3-1)); yuv[i]=Lookup_YUV(pixels[i]); }
        int pattern = Difference_Pattern(pixels, yuv);
'''+calls+'''
    }
    for (int y=0; y<params.factor; ++y) for (int x=0; x<params.factor; ++x)
        Write(coord*params.factor+ivec2(x,y), output[y*params.factor+x]);
}
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(re.sub(r"\boutput\b", "result_pixels", shader))


if __name__ == "__main__":
    main()
