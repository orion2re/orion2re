"""Generate JSON Schema and a Markdown reference from the canonical P0 contract bundle."""

import argparse
import hashlib
import html
import json
import os
from pathlib import Path
import sys
import tempfile

import audit_rpc_contract as audit


ROOT = Path(__file__).resolve().parents[1]
SOURCES = ("methods.json", "contracts.json", "field_policies.json")
NOTICE = "Generated by tools/generate_rpc_schema.py from specs/rpc/{methods,contracts,field_policies}.json; do not edit."


def Reference(name):
    return {"$ref": f"#/$defs/{name}"}


def Build_Schema(registry, contracts, policies):
    definitions = {}
    for name, source in sorted(contracts["types"].items()):
        kind = source["kind"]
        if kind == "object":
            schema = {"type": "object", "additionalProperties": False,
                      "properties": {field: dict(Reference(target), **{
                          "x-rpc-policy": source.get("fieldPolicies", {}).get(field, source["policy"])})
                          for field, target in source["fields"].items()},
                      "required": [field for field in source["fields"] if field not in source.get("optional", [])],
                      "x-rpc-policy": source["policy"]}
        elif kind == "array":
            schema = {"type": "array", "items": Reference(source["items"]), "maxItems": source["maxItems"]}
            if "minItems" in source:
                schema["minItems"] = source["minItems"]
            if source.get("unique"):
                schema["uniqueItems"] = True
        elif kind == "union":
            schema = {"oneOf": [Reference(variant) for variant in source["variants"]]}
        elif kind == "enum":
            schema = {"type": "string", "enum": source["values"]}
        elif kind == "string":
            schema = {"type": "string", "minLength": source["minBytes"] if source.get("ascii") else int(source["minBytes"] > 0),
                      "maxLength": source["maxBytes"], "x-minUtf8Bytes": source["minBytes"],
                      "x-maxUtf8Bytes": source["maxBytes"]}
            if "pattern" in source:
                schema["pattern"] = "^(?:" + source["pattern"] + r")(?![\s\S])"
            if "maxDecimal" in source:
                schema["x-maxDecimal"] = source["maxDecimal"]
        elif kind == "integer":
            schema = {"type": "integer", "minimum": source["min"], "maximum": source["max"],
                      "x-integerToken": True}
        else:
            schema = {"type": "boolean"}
        if "unit" in source:
            schema["x-unit"] = source["unit"]
            schema["description"] = contracts["units"][source["unit"]]
        definitions[name] = schema

    definitions["RpcRequestId"] = {"oneOf": [
        {"type":"string", "minLength":1, "maxLength":contracts["limits"]["requestIdBytes"],
         "x-maxUtf8Bytes":contracts["limits"]["requestIdBytes"]},
        {"type":"integer", "minimum":-9007199254740991, "maximum":9007199254740991,
         "x-integerToken":True}]}
    methods = []
    requests = []
    for method in sorted(registry["methods"], key=lambda item: item["name"]):
        name = method["name"]
        request_type, result_type = contracts["methods"][name]
        request_name = "Request_" + name.replace(".", "_")
        response_name = "Response_" + name.replace(".", "_")
        required = ["jsonrpc", "id", "method"]
        request_shape = contracts["types"][request_type]
        if set(request_shape["fields"]) - set(request_shape.get("optional", [])):
            required.append("params")
        definitions[request_name] = {
            "type":"object", "additionalProperties":False, "required":required,
            "properties":{"jsonrpc":{"const":"2.0"}, "id":Reference("RpcRequestId"),
                          "method":{"const":name}, "params":Reference(request_type)}}
        definitions[response_name] = {
            "type":"object", "additionalProperties":False, "required":["jsonrpc","id","result"],
            "properties":{"jsonrpc":{"const":"2.0"}, "id":Reference("RpcRequestId"),
                          "result":Reference(result_type)}}
        requests.append(Reference(request_name))
        methods.append(dict(method, implemented=name in registry["implementedMethods"], requestType=request_type, resultType=result_type,
                            request=Reference(request_name), response=Reference(response_name)))
    notifications = {}
    for name, params in sorted(contracts["notifications"].items()):
        definition = "Notification_" + name.replace(".", "_")
        definitions[definition] = {
            "type":"object", "additionalProperties":False, "required":["jsonrpc","method","params"],
            "properties":{"jsonrpc":{"const":"2.0"}, "method":{"const":name}, "params":Reference(params)}}
        notifications[name] = Reference(definition)
    errors = []
    for code, message in contracts["errors"].items():
        errors.append({"type":"object", "additionalProperties":False, "required":["code","message"],
                       "properties":{"code":{"const":int(code)}, "message":{"const":message}}})
    definitions["RpcErrorResponse"] = {
        "type":"object", "additionalProperties":False, "required":["jsonrpc","id","error"],
        "properties":{"jsonrpc":{"const":"2.0"},
                      "id":{"anyOf":[Reference("RpcRequestId"),{"type":"null"}]},
                      "error":{"oneOf":errors}}}
    digest = hashlib.sha256(json.dumps([registry, contracts, policies], sort_keys=True,
                                      separators=(",", ":")).encode()).hexdigest()
    return {"$schema":"https://json-schema.org/draft/2020-12/schema",
            "$id":"urn:orion2re:rpc:contract:0", "$comment":NOTICE,
            "title":"Orion2 RPC client request contracts (optional runtime, disabled by default)",
            "description":"Root includes planned acknowledged client request contracts; only x-rpc-implementedMethods are dispatchable in an enabled build. Response and server-notification entry points are in $defs. UTF-8 byte, lexical integer, depth, duplicate-key and authorization rules require the protocol guards; x-* annotations are not standard JSON Schema assertions.",
            "oneOf":requests, "$defs":definitions, "x-rpc-methods":methods,
            "x-rpc-notifications":notifications, "x-rpc-policies":policies["policies"],
            "x-rpc-limits":contracts["limits"], "x-rpc-sourceHash":digest,
            "x-rpc-runtimeEnabled":False, "x-rpc-implementedMethods":registry["implementedMethods"]}


def Cell(value):
    return html.escape(str(value)).replace("|", "\\|").replace("\n", "<br>")


def Type_Label(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    return schema.get("type", "union")


def Render_Markdown(schema):
    lines = [f"<!-- {NOTICE} -->", "# RPC contract reference", "",
             "**Optional runtime, disabled by default.** Only the implemented methods listed below are callable when the RPC build and settings enable it.", "",
             "Implemented methods: " + ", ".join(f"`{name}`" for name in schema["x-rpc-implementedMethods"]) + ".", "",
             "This document is rendered from `schema.json`, not a second method catalog.",
             "The root schema validates acknowledged client requests; per-method success responses and server notifications have separate definitions.",
             "All fields are non-null unless explicitly stated. Unknown keys are rejected. UTF-8 byte limits, lexical integer tokens, duplicate keys, depth and authorization need the protocol guards in addition to standard JSON Schema validation.", "",
             f"Source bundle SHA-256: `{schema['x-rpc-sourceHash']}`.", "", "## Methods", "",
             "| Method | Owner | Role | Availability | Params | Result |",
             "| --- | --- | --- | --- | --- | --- |"]
    for method in schema["x-rpc-methods"]:
        lines.append("| " + " | ".join(Cell(method[key]) for key in
                     ("name", "owner", "role", "availability", "requestType", "resultType")) + " |")
    lines += ["", "## Types", ""]
    envelope_prefixes = ("Request_", "Response_", "Notification_")
    for name, definition in schema["$defs"].items():
        if name.startswith(envelope_prefixes) or name in ("RpcRequestId", "RpcErrorResponse"):
            continue
        lines += [f"### {name}", ""]
        if "description" in definition:
            lines += [Cell(definition["description"]), ""]
        if definition.get("type") == "object":
            lines += ["| Field | Type | Required | Policy |", "| --- | --- | --- | --- |"]
            for field, prop in definition["properties"].items():
                lines.append(f"| {Cell(field)} | {Cell(Type_Label(prop))} | "
                             f"{'yes' if field in definition['required'] else 'no'} | {Cell(prop['x-rpc-policy'])} |")
        elif "enum" in definition:
            lines.append("Values: " + ", ".join(f"`{Cell(value)}`" for value in definition["enum"]) + ".")
        elif "oneOf" in definition:
            lines.append("Exactly one of: " + ", ".join(Type_Label(variant) for variant in definition["oneOf"]) + ".")
        elif definition.get("type") == "array":
            lines.append(f"Array of `{Type_Label(definition['items'])}`; "
                         f"{definition.get('minItems', 0)}..{definition['maxItems']} items; "
                         f"unique: {str(definition.get('uniqueItems', False)).lower()}.")
        else:
            constraints = {key: value for key, value in definition.items()
                           if key not in ("description", "x-unit")}
            lines.append("Constraints: `" + json.dumps(constraints, sort_keys=True) + "`.")
        lines.append("")
    lines += ["## Server notifications", "", "| Notification | Schema |", "| --- | --- |"]
    for name, reference in schema["x-rpc-notifications"].items():
        lines.append(f"| {Cell(name)} | {Cell(Type_Label(reference))} |")
    lines += ["", "## Field policies", "", "Reviewed means static evidence, not runtime visibility approval.", "",
              "| Policy | Status | Predicate | Native sources | Planned tests |", "| --- | --- | --- | --- | --- |"]
    for name, policy in schema["x-rpc-policies"].items():
        sources = "; ".join(f"{path}: {symbol}" for path, symbol in policy["sources"])
        lines.append("| " + " | ".join(Cell(value) for value in
                     (name, policy["status"], policy["predicate"], sources, ", ".join(policy["tests"]))) + " |")
    lines += ["", "## Provisional limits", "", "These do not close the native maximum-game profiling gate.", ""]
    lines.extend(f"- **{Cell(key)}:** {Cell(value)}" for key, value in schema["x-rpc-limits"].items())
    lines += ["", "## Errors", "", "| Code | Message |", "| --- | --- |"]
    for error in schema["$defs"]["RpcErrorResponse"]["properties"]["error"]["oneOf"]:
        lines.append(f"| {error['properties']['code']['const']} | {Cell(error['properties']['message']['const'])} |")
    return "\n".join(lines) + "\n"


def Render_Cpp_Header(registry, contracts):
    limits = contracts["limits"]
    lines = ["// Generated by tools/generate_rpc_schema.py from specs/rpc; do not edit.",
             "#pragma once", "", '#include "rpc/rpc_protocol.h"', "",
             "namespace rpc::contract_data {",
             "    struct s_error_descriptor {",
             "        int32_t code;",
             "        const char* message;",
             "    };", "",
             f"    inline constexpr size_t RPC_MAX_INPUT_BYTES = {limits['inputBytes']};",
             f"    inline constexpr uint32_t RPC_MAX_DEPTH = {limits['depth']};",
             f"    inline constexpr size_t RPC_MAX_REQUEST_ID_BYTES = {limits['requestIdBytes']};", "",
             "    extern const s_protocol_limits rpc_limits;",
             f"    extern const s_method_descriptor rpc_methods[{len(registry['methods'])}];",
             f"    extern const s_error_descriptor rpc_errors[{len(contracts['errors'])}];",
             "    std::string Types_Json();",
             "} // namespace rpc::contract_data", ""]
    return "\n".join(lines)


def Render_Cpp(registry, contracts):
    limits = contracts["limits"]
    lines = ["// Generated by tools/generate_rpc_schema.py from specs/rpc; do not edit.",
             '#include "rpc_contract_data.h"', "", "namespace rpc::contract_data {",
             "    const s_protocol_limits rpc_limits = {",
             "        RPC_MAX_INPUT_BYTES, RPC_MAX_DEPTH, RPC_MAX_REQUEST_ID_BYTES,",
             f"        {limits['authenticationDeadlineMs']}, {limits['outputBytesPerConnection']}, {limits['outputBytesGlobal']},",
             f"        {limits['outputMessagesPerConnection']}, {limits['messagesPerSecond']}, {limits['receiveCallbacksPerSecond']},",
             f"        {limits['requestTimeoutMs']}, {limits['commandsPerGamePoll']}, {limits['gamePollBudgetUs']}, {limits['minimumCaptureIntervalMs']}",
             "    };", "    const s_method_descriptor rpc_methods[] = {"]
    for method in registry["methods"]:
        request, result = contracts["methods"][method["name"]]
        strings = [method["name"], request, result, method["role"], method["availability"]]
        implemented = "true" if method["name"] in registry["implementedMethods"] else "false"
        lines.append("        {" + ", ".join(json.dumps(value) for value in strings) + ", " + implemented + "},")
    lines += ["    };", "    const s_error_descriptor rpc_errors[] = {"]
    for code, message in contracts["errors"].items():
        lines.append(f"        {{{code}, {json.dumps(message)}}},")
    lines.append("    };")
    types = json.dumps(contracts["types"], ensure_ascii=True, separators=(",", ":"))
    if ')rpc_types"' in types:
        raise ValueError("contract contains the reserved C++ raw-string delimiter")
    # Separate array elements avoid MSVC's limits on both individual and concatenated literals.
    lines += ["", "    std::string Types_Json() {", "        static constexpr const char* chunks[] = {"]
    lines.extend('            R"rpc_types(' + types[offset:offset + 4096] + ')rpc_types",'
                 for offset in range(0, len(types), 4096))
    lines += ["        };", "        std::string json;", f"        json.reserve({len(types)});",
              "        for (const char* chunk : chunks) json += chunk;", "        return json;", "    }",
              "} // namespace rpc::contract_data", ""]
    return "\n".join(lines)


def Write_Output(path, content):
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                         dir=path.parent, delete=False) as output:
            temporary = Path(output.name)
            output.write(content)
        os.replace(temporary, path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if checked-in schema/reference are stale; do not write")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "specs/rpc/generated")
    args = parser.parse_args()
    try:
        registry, contracts, policies = [audit.Load_Json(ROOT / "specs/rpc" / name) for name in SOURCES]
        plan = (ROOT / "plan.md").read_text(encoding="utf-8")
        audit.Validate_Methods(registry, audit.Catalog_Methods(plan))
        audit.Validate_Contracts(ROOT, registry, contracts, policies)
        schema = Build_Schema(registry, contracts, policies)
        encoded = json.dumps(schema, indent=2, ensure_ascii=False) + "\n"
        # Deliberately render the serialized schema so documentation consumes only the interchange artifact.
        outputs = {args.output_dir / "schema.json":encoded,
                   args.output_dir / "reference.md":Render_Markdown(json.loads(encoded))}
        if args.output_dir.resolve() == (ROOT / "specs/rpc/generated").resolve():
            outputs[ROOT / "src/rpc/generated/rpc_contract_data.h"] = Render_Cpp_Header(registry, contracts)
            outputs[ROOT / "src/rpc/generated/rpc_contract_data.cpp"] = Render_Cpp(registry, contracts)
        for path, content in outputs.items():
            if args.check:
                if not path.is_file() or path.read_text(encoding="utf-8") != content:
                    raise ValueError(f"stale generated artifact: {path}; run tools/generate_rpc_schema.py")
            else:
                Write_Output(path, content)
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"RPC schema generation failed: {error}", file=sys.stderr)
        return 1
    print("RPC schema/reference are current" if args.check else "Generated RPC schema and reference")
    return 0


if __name__ == "__main__":
    sys.exit(main())
