static uint8_t Galaxy_Size_For_Classic_Rules_(uint8_t galaxy_size) {
    if (galaxy_size == GALAXY_SIZE_CLUSTER) {
        return GALAXY_SIZE_HUGE;
    }
    return galaxy_size;
}

static uint8_t Starting_Civilization_Level_For_Classic_Rules_(uint8_t civilization_level) {
    if (civilization_level == STARTING_CIVILIZATION_LEVEL_PRE_WARP ||
        civilization_level == STARTING_CIVILIZATION_LEVEL_AVERAGE ||
        civilization_level == STARTING_CIVILIZATION_LEVEL_ADVANCED) {
        return civilization_level;
    }
    if (civilization_level == STARTING_CIVILIZATION_LEVEL_POST_WARP) {
        return STARTING_CIVILIZATION_LEVEL_AVERAGE;
    }
    return STARTING_CIVILIZATION_LEVEL_AVERAGE;
}

